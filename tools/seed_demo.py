#!/usr/bin/env python3
"""Put the synthetic test video into a dashboard data directory, so the whole
dashboard can be tried without real footage or YOLO.

  python tools/seed_demo.py               # uses backend/data (or $RLV_DATA_DIR)
  python tools/seed_demo.py --data /tmp/rlv --analyse

The video is labelled "SYNTHETIC test scene" and not Cape Coast footage.
"""
from __future__ import annotations

import argparse
import os
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
sys.path.insert(0, str(ROOT))

from app.service import Service  # noqa: E402
from tools.make_synthetic_video import generate  # noqa: E402


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--data", default=os.environ.get("RLV_DATA_DIR", str(ROOT / "backend" / "data")))
    ap.add_argument("--analyse", action="store_true", help="also run an analysis with the scripted detector")
    args = ap.parse_args(argv)
    svc = Service(args.data)
    with tempfile.TemporaryDirectory() as tmp:
        video = Path(tmp) / "synthetic_junction.mp4"
        generate(video)
        v = svc.add_video_from_path(video, location="SYNTHETIC test scene (not real footage)",
                                    is_cape_coast=False, session="synthetic", notes="Generated by tools/make_synthetic_video.py")
    print(f"Added video #{v['id']} to {args.data}")
    if args.analyse:
        a = svc.start_analysis(v["id"], model="scripted")
        a = svc.wait(a["id"])
        print(f"Analysis #{a['id']}: {a['status']} {a['stats']['counts'] if a['stats'] else a['error']}")
    svc.shutdown()
    return 0


if __name__ == "__main__":
    sys.exit(main())
